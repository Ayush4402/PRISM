#!/usr/bin/env python3
"""
Plot cumulative base-table rows and query-result rows for the OJ chain.

The plot follows the dimensions and typography used by the individual
figures generated by prism_oj_why.py.

Output:
    oj_table_and_result_rows.png
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter, NullFormatter


# =============================================================================
# DATA AND CONFIGURATION
# =============================================================================

# Query identifiers.
QIDS = ["1", "2", "3", "4", "5", "6", "7"]

# Cumulative rows in all base tables participating in each query.
BASE_TABLE_ROWS = [
    30,
    10_030,
    810_030,
    1_010_030,
    7_011_245,
    8_511_245,
    8_661_245,
]

# Output cardinality of each query.
QUERY_RESULT_ROWS = [
    25,
    10_000,
    800_000,
    800_000,
    24_004_860,
    24_004_860,
    24_004_860,
]

COLORS = {
    "deep_green": "#006400",
    "red": "#c44e52",
}

FIGURE_SIZE = (6.6, 4.8)
FONT_SIZE = 16
LINE_WIDTH = 3
MARKER_SIZE = 70
OUTPUT_DPI = 200
OUTPUT_FILE = "oj_table_and_result_rows.png"


# =============================================================================
# FORMATTING HELPERS
# =============================================================================


def human(value, _position=None):
    """Format axis values using K, M, or B suffixes."""
    value = float(value)
    magnitude = abs(value)

    if magnitude >= 1_000_000_000:
        return f"{value / 1_000_000_000:.3g}B"

    if magnitude >= 1_000_000:
        return f"{value / 1_000_000:.3g}M"

    if magnitude >= 1_000:
        return f"{value / 1_000:.3g}K"

    return f"{value:g}"


def style(ax, xlabel, ylabel, fontsize=16):
    """Apply the formatting used by the other OJ plots."""
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)

    ax.tick_params(
        axis="both",
        labelsize=fontsize,
    )

    ax.xaxis.label.set_size(fontsize + 2)
    ax.yaxis.label.set_size(fontsize + 2)

    ax.grid(
        True,
        alpha=0.3,
    )


def ensure_parent_directory(filename):
    """Create the output directory if necessary."""
    output_path = Path(filename).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)


# =============================================================================
# PLOTTING
# =============================================================================


def plot_row_counts(ax, fontsize=16):
    """
    Plot cumulative base-table rows and query-result rows.

    The base-table series is shown in deep green, and the query-result
    series is shown in red.
    """
    x_positions = list(range(1, len(QIDS) + 1))

    # Deep-green cumulative base-table series.
    ax.plot(
        x_positions,
        BASE_TABLE_ROWS,
        color=COLORS["deep_green"],
        linewidth=LINE_WIDTH,
        label="Cumulative base-table rows",
        zorder=2,
    )

    ax.scatter(
        x_positions,
        BASE_TABLE_ROWS,
        s=MARKER_SIZE,
        color=COLORS["deep_green"],
        edgecolor=COLORS["deep_green"],
        linewidth=2,
        zorder=3,
    )

    # Red query-result cardinality series.
    ax.plot(
        x_positions,
        QUERY_RESULT_ROWS,
        color=COLORS["red"],
        linewidth=LINE_WIDTH,
        label="Query-result rows",
        zorder=2,
    )

    ax.scatter(
        x_positions,
        QUERY_RESULT_ROWS,
        s=MARKER_SIZE,
        color=COLORS["red"],
        edgecolor=COLORS["red"],
        linewidth=2,
        zorder=3,
    )

    # Use the same linear cardinality range as the OJ cardinality plot.
    ax.set_ylim(0, 24_500_000)

    ax.yaxis.set_major_formatter(
        FuncFormatter(human)
    )
    ax.yaxis.set_minor_formatter(
        NullFormatter()
    )

    style(
        ax,
        "#OJs",
        "Number of rows, TPC-H SF 1",
        fontsize,
    )

    ax.set_xticks(x_positions)
    ax.set_xticklabels(QIDS)

    # Match the slightly smaller X-axis tick labels used by the
    # cardinality plot in prism_oj_why.py.
    ax.tick_params(
        axis="x",
        labelsize=fontsize - 3,
    )

    ax.legend(
        fontsize=fontsize - 4,
        loc="upper left",
    )


def save_figure(fig, filename, dpi=200):
    """Save and close the generated figure."""
    ensure_parent_directory(filename)

    fig.tight_layout()

    fig.savefig(
        filename,
        dpi=dpi,
        bbox_inches="tight",
    )

    plt.close(fig)

    print("saved", filename)


# =============================================================================
# MAIN
# =============================================================================


def main():
    # This matches the 6.6 × 4.8-inch dimensions of the individual plots
    # generated by prism_oj_why.py.
    fig, ax = plt.subplots(
        figsize=FIGURE_SIZE
    )

    plot_row_counts(
        ax,
        fontsize=FONT_SIZE,
    )

    save_figure(
        fig,
        OUTPUT_FILE,
        dpi=OUTPUT_DPI,
    )


if __name__ == "__main__":
    main()